/** Habitats de l'espèce : la donnée de la source si elle existe, sinon l'estimation par classification. */
export function speciesHabitats(s: Pick<Species, 'habitats' | 'taxonomy'>): { habitats: HabitatCode[]; estimated: boolean } {
  if (s.habitats.length) return { habitats: s.habitats, estimated: false };
  const t = s.taxonomy;
  const guess = [t.genus, t.family, t.order, t.class].map((k) => (k ? BY_TAXON[k] : undefined)).find(Boolean);
  return { habitats: guess ? [guess] : [], estimated: !!guess };
}
